"""The body-FORM vocabulary: what a drawing may stand for.

THE DEFECT THIS REPLACES. An icon used to be chosen by matching substrings of
the taxon's NAME against an ordered table (life.ICON_RULES), and anything that
matched nothing drew the fallback for its REALM: land -> a monitor lizard, sea
-> a palaeoniscid fish. Realm "land" holds plants as well as animals, so the
fallback drew Acacia, Picea and Bison as the same lizard -- 124 taxa -- and kelp,
krill, reef corals and papyrus as the same fish. And where a rule did match it
matched a drawing far too coarse to be right: "carnivore" is a coyote, so Ursus
was a coyote; "mammal" is an opossum, so Megatherium, Litopterna and
Notoungulata were opossums.

Both halves were structural. A name is not a classification, so the table could
only ever be as complete as the last person's memory of what was in the data;
and a fallback that always succeeds makes every omission invisible.

WHAT THIS IS INSTEAD. Every organism in the registry (build/taxa/*.json)
declares its FORM -- the body plan a reader would recognise -- and every form
declares the one drawing that stands for it. There is no realm fallback at all:
a taxon whose form has no drawing fails the build. A form may name a PARENT,
which is a *declared* approximation (a brontothere drawn as a rhino) that the
audit counts and can ratchet down, as opposed to a silent one.

`of` lists the Paleobiology Database clades a form legitimately depicts, and is
how a wrong binding gets caught without anyone looking: Ursus is in Ursidae,
"canid" is `of` Canidae, so Ursus-as-canid is a finding. See biota.check_form().

`terms` are what build_silhouettes asks PhyloPic for, in order, when the form
needs a drawing of its own. `icon` names an existing drawing when its key
differs from the form's (the coyote was filed under "carnivore").

Kinds: animal | plant | fungus | alga | protist | microbe | deposit
A card's FAUNA are its animals; its FLORA are plants, fungi, algae and lichens;
protists, microbes and deposits are listed as what they are.
"""

