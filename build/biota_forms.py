def kinds():
    return {k: v["kind"] for k, v in FORMS.items()}


def chain(form):
    """The form, then its declared parents, nearest first."""
    out, seen = [], set()
    while form and form not in seen and form in FORMS:
        out.append(form)
        seen.add(form)
        form = FORMS[form]["parent"]
    return out


